import assert from 'node:assert/strict';
import { complianceIssue, complianceIssues, bookingTimeIssue, defaultBookingStart } from '../../../previews/PKG-02B/v13/readiness-contract.ts';

const today = '2026-09-22';
const wof = {name:'WoF',applies:'Applicable',basis:'DEMO vehicle assessment',outcome:'Passed',evidence:'DEMO certificate',due:'2027-04-09',low:0,high:0};
const ruc = {...wof,name:'RUC',outcome:'Recorded',evidence:'DEMO licence',due:'',low:80000,high:90000};
assert.equal(complianceIssue(wof,82460,today),'');
assert.match(complianceIssue({...wof,outcome:'Needs assessment'},82460,today),/assessment is unresolved/);
assert.match(complianceIssue({...wof,outcome:'Needs assessment',evidence:'',due:''},82460,today),/assessment is unresolved/);
assert.match(complianceIssue({...wof,outcome:'Failed'},82460,today),/failed evidence/);
assert.match(complianceIssue({...wof,applies:'Unknown'},82460,today),/assess applicability/);
assert.match(complianceIssue({...wof,evidence:''},82460,today),/evidence is missing/);
assert.match(complianceIssue({...wof,due:'2026-09-21'},82460,today),/expired/);
assert.equal(complianceIssue({...wof,applies:'Not applicable',outcome:'Needs assessment',evidence:'',due:''},82460,today),'');
assert.match(complianceIssue({...wof,applies:'Not applicable',basis:''},82460,today),/basis/);
assert.equal(complianceIssue(ruc,82460,today),'');
assert.match(complianceIssue({...ruc,high:82000},82460,today),/recorded odometer 82,460 km.*82,000 km/);
assert.equal(complianceIssue({...ruc,high:82460},82460,today),'','Existing strict-greater comparison retained, no invented threshold');
assert.match(complianceIssue(ruc,90001,today,'checkout observation'),/checkout observation 90,001 km/);
assert.match(complianceIssue(ruc,0,today),/record an odometer observation/);
assert.equal(complianceIssue({...ruc,applies:'Not applicable',high:82000},82460,today),'');
const original = structuredClone(ruc);
assert.equal(complianceIssues([wof,ruc],82460,today).length,0);
assert.equal(complianceIssues([{...wof,outcome:'Needs assessment'},{...ruc,high:82000}],82460,today).length,2);
assert.deepEqual(ruc,original,'Assessment does not overwrite recorded evidence or mileage');
assert.equal(defaultBookingStart(),'2026-09-22T10:00');
assert.equal(defaultBookingStart('2026-09-21'),'2026-09-22T10:00');
assert.equal(defaultBookingStart('2026-09-23'),'2026-09-23T09:00');
assert.equal(bookingTimeIssue('2026-09-22T09:00','2026-09-22T10:00').field,'start-time');
assert.equal(bookingTimeIssue('2026-09-21T09:00','2026-09-21T10:00').field,'start-date');
assert.equal(bookingTimeIssue('2026-09-22T09:30','2026-09-22T10:00'),null);
assert.equal(bookingTimeIssue('2026-09-21T09:00','2026-09-21T10:00',true),null,'Supported historical edits remain valid');
assert.equal(bookingTimeIssue('2026-09-23T10:00','2026-09-23T09:00').field,'end-time');
assert.match(bookingTimeIssue('2026-09-23T09:00','2026-09-23T10:00',false,'Busy').message,/Busy/);
console.log('PASS: 27 evidence, coverage, provenance, time-default and focus-target assertions. Workflow transitions verified separately in browser.');
