import assert from 'node:assert/strict';
import { documentReminders, saveDocument, suggestedRenewalTime, validateDocument } from '../../../previews/PKG-02B/v12/document-workflow.ts';

const seed = { documents: [], followups: [], profile: { history: [], insuranceDue: '2026-12-31' }, compliance: [{ due: '2026-10-08' }], restriction: true };
const values = { category: 'Insurance policy', reference: 'TEST-12', issued: '2026-09-22', expiry: '2026-12-31', finance: 'FA-DEMO-14', reason: 'Synthetic test', remind: 'true', remindAt: '2026-12-01T09:00', reminderOwner: 'Coordinator', reminderBackup: 'Manager' };
const files = [{ id: 'file-a', name: 'policy.png', url: 'blob:original-a' }, { id: 'file-b', name: 'schedule.png', url: 'blob:original-b' }];
assert.equal(validateDocument(values), '');
assert.match(validateDocument({ ...values, expiry: '' }), /expiry date/);
assert.match(validateDocument({ ...values, expiry: '2026-09-01' }), /on or after/);
assert.match(validateDocument({ ...values, remindAt: '2026-09-22T09:00' }), /future/);
assert.match(validateDocument({ ...values, remindAt: '2027-01-01T09:00' }), /on or before/);
assert.match(validateDocument({ ...values, reminderOwner: '' }), /owner/);
assert.equal(validateDocument({ ...values, expiry: '', remind: 'false' }), '');
assert.equal(suggestedRenewalTime('2026-12-31'), '2026-12-01T09:00');
assert.equal(suggestedRenewalTime('2026-10-01'), '2026-09-23T09:00');

let data = saveDocument(seed, values, files);
assert.equal(data.documents.length, 2);
assert.equal(data.followups.length, 1, 'multi-file upload creates one reminder');
const reminderId = data.followups[0].id;
assert.equal(documentReminders(data, data.documents[1])[0].id, reminderId);
assert.equal(data.profile.insuranceDue, seed.profile.insuranceDue);
assert.equal(data.compliance, seed.compliance);
assert.equal(data.restriction, true);
data = saveDocument(data, { ...values, expiry: '2027-01-31', remindAt: '2027-01-01T10:30' }, [], data.documents[0], true);
assert.equal(data.documents.length, 2, 'metadata edit needs no upload');
assert.ok(data.documents.every((f) => f.expiry === '2027-01-31'));
assert.equal(data.documents[0].url, 'blob:original-a');
assert.equal(data.followups.length, 1);
assert.equal(data.followups[0].id, reminderId);
assert.equal(data.followups[0].at, '2027-01-01T10:30');
data = saveDocument(data, values, [{ id: 'file-c', name: 'renewed.png', url: 'blob:new' }], data.documents[0]);
assert.equal(data.documents.filter((f) => f.status === 'Superseded').length, 2);
assert.equal(data.documents[0].url, 'blob:original-a');
assert.equal(data.followups[0].source, 'file-c');
assert.equal(data.followups[0].id, reminderId);
assert.equal(data.followups.length, 1);
data = saveDocument(data, { ...values, remind: 'false', expiry: '' }, [], data.documents[2], true);
assert.equal(data.followups[0].status, 'Paused');
data = saveDocument(data, values, [], data.documents[2], true);
assert.equal(data.followups[0].status, 'Scheduled');
assert.equal(data.followups.length, 1, 'rescheduling reuses the same reminder');
data.followups[0].status = 'Completed';
data = saveDocument(data, values, [{ id: 'file-d', name: 'next.png' }], data.documents[2]);
assert.equal(data.followups[0].status, 'Completed');
assert.equal(data.followups[0].source, 'file-c', 'completed history retains its original source');
assert.equal(data.followups.length, 2);
assert.equal(data.followups[1].source, 'file-d');
assert.equal(saveDocument(seed, values, []), seed, 'empty upload cannot write a partial record');
console.log('PASS: document dates, owner validation, grouped upload, metadata edits, replacement lineage, reminder deduplication, pause/resume and source boundaries.');
