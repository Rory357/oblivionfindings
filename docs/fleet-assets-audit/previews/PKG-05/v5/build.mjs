import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import crypto from 'node:crypto';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.resolve(here,'../../../../..');
const deps='C:/Users/steph/Herd/oblivionfindings/node_modules';
const require=createRequire(path.join(deps,'../package.json'));
const {build}=require('esbuild');
const {compile}=require('@tailwindcss/node');
const {Scanner}=require('@tailwindcss/oxide');
await fs.mkdir(path.join(here,'dist'),{recursive:true});
const result=await build({entryPoints:[path.join(here,'app.tsx')],bundle:true,format:'esm',platform:'browser',jsx:'automatic',nodePaths:[deps],alias:{'@':path.join(root,'resources/js')},outfile:path.join(here,'dist/app.js'),metafile:true,sourcemap:true,define:{'process.env.NODE_ENV':'"production"'},minify:true});
const dependencies=new Set();
const source=await fs.readFile(path.join(root,'resources/css/app.css'),'utf8');
const compiler=await compile(source,{base:path.join(root,'resources/css'),onDependency:p=>dependencies.add(p),customCssResolver:async id=>id==='tailwindcss'?path.join(deps,'tailwindcss/index.css'):id==='tw-animate-css'?path.join(deps,'tw-animate-css/dist/tw-animate.css'):undefined});
const scanner=new Scanner({sources:[{base:path.join(root,'resources/js/components'),pattern:'**/*.{tsx,ts}',negated:false},{base:path.join(root,'resources/js/pages/sites/calendar'),pattern:'*.tsx',negated:false},{base:here,pattern:'*.tsx',negated:false}]});
await fs.writeFile(path.join(here,'dist/app.css'),compiler.build(scanner.scan()));
const inputs=[...new Set([...Object.keys(result.metafile.inputs).map(p=>path.resolve(p)),...dependencies,path.join(root,'resources/css/app.css')])].filter(p=>!p.includes('node_modules'));
const inputHashes=await Promise.all(inputs.map(async p=>({path:p,sha256:crypto.createHash('sha256').update(await fs.readFile(p)).digest('hex')})));
await fs.writeFile(path.join(here,'build-inputs.json'),JSON.stringify({baseline:'4ea64c547ed85a5b7504e59599db351f6eba7deb',inputs:inputHashes},null,2)+'\n');
console.log(`Built PKG-05 v5 with ${inputHashes.length} hashed source inputs. No application files changed.`);
